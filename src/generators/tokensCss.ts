import { toCssVars } from '@/tokens/cssVars';
import type { DesignTokens } from '@/tokens/deriveTokens';
import { fixAccent, generatePalette } from '@/tokens/palette';
import type { DesignConfig } from '@/tokens/types';
import { beforeYouFinishComment, styleTitle } from './shared';

const kebab = (name: string) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function darkBlock(config: DesignConfig): string[] {
  const draft = generatePalette(config.accent, config.neutral, 'dark');
  const palette = generatePalette(fixAccent(config.accent, draft), config.neutral, 'dark');
  const lines = Object.entries(palette).map(
    ([role, value]) => `  --bb-color-${kebab(role)}: ${value};`,
  );
  return ['', '/* Optional dark mode: set data-theme="dark" on <html>. */', ':root[data-theme="dark"] {', '  color-scheme: dark;', ...lines, '}'];
}

export function tokensCss(config: DesignConfig, tokens: DesignTokens): string {
  const variables = Object.entries(toCssVars(tokens)).map(([name, value]) => `  ${name}: ${value};`);
  return [
    `/* ${styleTitle(config)} design tokens. Generated by Dress Code. */`,
    ':root {',
    `  color-scheme: ${config.theme};`,
    ...variables,
    '}',
    ...(config.theme === 'light' ? darkBlock(config) : []),
    '',
    beforeYouFinishComment('/*', ' */', ' * '),
    '',
  ].join('\n');
}
